#!/bin/bash
# Writes THIRD_PARTY_NOTICES: for every module linked into the pllum-connect binary, its path, version and the full text of
# its licence files (LICENSE*, LICENCE*, COPYING*, NOTICE*, PATENTS), read from the Go module cache. Offline: nothing is
# downloaded, so the modules must already be in the cache (go mod download). The standard library and this repository's own
# module are left out; the Go standard library's licence is Go's own, and this repository's is LICENSE.
#   scripts/notices.sh          rewrites THIRD_PARTY_NOTICES
#   scripts/notices.sh --check  fails if the committed THIRD_PARTY_NOTICES is out of date (CI runs this)
# Licence files nested in the folders of linked packages are included too, labelled with their path in the module.
# Fails, naming the module, if a linked module has no licence file, except the one named in borrowed_from below. A module replaced in go.mod (Beeper's req fork, the
# patched mautrix-linkedin copy in third_party/) is listed as the module that is actually built, with its own licence files.
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="/opt/homebrew/bin:$PATH"
fail() { echo "error: notices: $*" >&2; exit 1; }
mode="${1:-write}"
[[ "$mode" == write || "$mode" == --check ]] || fail "usage: scripts/notices.sh [--check]"

# the same toolchain, target and no-network rules as the build (Pllum's scripts/build-connect.sh)
toolchain="$(awk '$1 == "toolchain" { print $2 }' go.mod)"
[[ -n "$toolchain" ]] && export GOTOOLCHAIN="$toolchain"
export GOOS=darwin GOARCH=arm64 CGO_ENABLED=0 GOPROXY=off GOFLAGS=-mod=readonly LC_ALL=C

# one line per linked package that belongs to a module other than this one: the module as built (a replacement wins), its
# version and its directory
modules="$(go list -deps -f '{{with .Module}}{{if not .Main}}{{if .Replace}}{{.Replace.Path}}|{{.Replace.Version}}|{{.Replace.Dir}}{{else}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}{{end}}' ./cmd/pllum-connect 2>&1)" \
  || fail "go list failed (modules missing from the cache? run go mod download): $modules"
modules="$(printf '%s\n' "$modules" | sed '/^$/d' | sort -u)"
[[ -n "$modules" ]] || fail "no linked modules found"

# Licences nested inside a linked package's own folder (a vendored or derived file, such as klauspost's zstd/internal/xxhash)
# apply to that package, so they are listed too. For every linked package, each folder from the package up to, but not
# including, its module's root: "module|folder relative to the module root", one line per folder.
nested="$(go list -deps -f '{{with .Module}}{{if not .Main}}{{if .Replace}}{{.Replace.Path}}|{{.Replace.Dir}}{{else}}{{.Path}}|{{.Dir}}{{end}}{{end}}{{end}}|{{.Dir}}' ./cmd/pllum-connect 2>&1)" \
  || fail "go list failed (modules missing from the cache? run go mod download): $nested"
nested="$(printf '%s\n' "$nested" | while IFS='|' read -r mpath mdir pdir; do
  [[ -n "$mpath" && -n "$mdir" ]] || continue
  d="$pdir"
  while [[ "$d" != "$mdir" && "$d" == "$mdir"/* ]]; do
    echo "$mpath|${d#"$mdir"/}"
    d="$(dirname "$d")"
  done
done | sort -u)"

# github.com/beeper/poly1305 is a copy of golang.org/x/crypto's chacha20poly1305 and poly1305 packages and ships no licence
# file of its own (nor does its repository); every one of its sources carries Go's "Copyright The Go Authors ... BSD-style
# license ... LICENSE file" header. So it is listed with golang.org/x/crypto's LICENSE, which that header names, and says so.
# Any other module without a licence file still fails the script.
borrowed_from() {
  case "$1" in
    github.com/beeper/poly1305) echo golang.org/x/crypto ;;
  esac
}
module_dir() { printf '%s\n' "$modules" | awk -F'|' -v p="$1" '$1 == p { print $3; exit }'; }
find_licences() { find "$1" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \) | sort; }

out="THIRD_PARTY_NOTICES"
dest="$out"
[[ "$mode" == --check ]] && dest="$out.check"
trap 'rm -f "$out.check"' EXIT

{
  echo "Third-party notices for Pllum Connect"
  echo
  echo "Pllum Connect (github.com/matwhiting/pllum-connect) is free software under the GNU AGPL-3.0 (see LICENSE). The Go modules"
  echo "below are linked into the pllum-connect program, each under its own licence, reproduced in full after its name. The Go"
  echo "standard library is used under Go's own licence (https://go.dev/LICENSE). Generated by scripts/notices.sh; do not edit."
  while IFS='|' read -r path version dir; do
    [[ -d "$dir" ]] || fail "$path's directory isn't in the module cache ($dir): run go mod download"
    files=()
    while IFS= read -r f; do files+=("$f"); done < <(find_licences "$dir")
    note=""
    if (( ${#files[@]} == 0 )); then
      lender="$(borrowed_from "$path")"
      [[ -n "$lender" ]] || fail "$path ${version:-(local)} is linked into the helper but has no LICENSE, COPYING or NOTICE file"
      lender_dir="$(module_dir "$lender")"
      [[ -n "$lender_dir" ]] || fail "$path has no licence file and $lender, whose LICENSE it borrows, isn't linked"
      while IFS= read -r f; do files+=("$f"); done < <(find_licences "$lender_dir")
      (( ${#files[@]} > 0 )) || fail "$lender has no licence file to lend $path"
      note="$path ships no licence file. Its sources are copies of $lender's code and carry that project's \"Copyright The Go Authors\" BSD-style licence header, so $lender's licence files follow."
    fi
    # then the licence files inside the folders of its linked packages, labelled by their path in the module
    labels=()
    for f in "${files[@]}"; do labels+=("$(basename "$f")"); done
    while IFS='|' read -r npath rel; do
      [[ "$npath" == "$path" ]] || continue
      while IFS= read -r f; do files+=("$f"); labels+=("$rel/$(basename "$f")"); done < <(find_licences "$dir/$rel")
    done <<< "$nested"
    echo
    echo "================================================================================"
    echo "${path} ${version:-(copy in this repository)}"
    [[ -z "$note" ]] || echo "$note"
    i=0
    for f in "${files[@]}"; do
      echo "--------------------------------------------------------------------------------"
      echo "${labels[$i]}"
      i=$((i + 1))
      echo "--------------------------------------------------------------------------------"
      cat "$f"
      [[ -z "$(tail -c1 "$f")" ]] || echo
    done
  done <<< "$modules"
} > "$dest"

if [[ "$mode" == --check ]]; then
  cmp -s "$dest" "$out" || fail "$out is out of date: run scripts/notices.sh and commit it"
  echo "$out is current ($(printf '%s\n' "$modules" | wc -l | tr -d ' ') modules)"
else
  echo "wrote $out ($(printf '%s\n' "$modules" | wc -l | tr -d ' ') modules)"
fi
